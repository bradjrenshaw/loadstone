// Before installing or updating, offer the list of the repo's releases so
// the user can pick a specific version (including pre-releases, which the
// default "latest" path never sees). The chosen release's own
// loadstone-release.json and assets are used. Falls back to plain latest
// if the list cannot be fetched.
void LoadstoneFrame::StartVersionPick(OpKind kind) {
    if (opInFlight_ || fetchInFlight_) return;
    fetchInFlight_ = true;
    DisablePageControlsKeepFocus();
    SetStatusText(T("gui-status-fetching-releases"));

    auto alive = alive_;
    std::string modId = ToStd(pageModId_);
    std::thread([alive, this, kind, modId] {
        std::vector<loadstone::ReleaseEntry> releases;
        std::string error;
        bool needsSignIn = false;
        try {
            auto fetched = loadstone::list_mod_releases(kEmbeddedProfile, modId);
            releases.assign(fetched.begin(), fetched.end());
        } catch (const std::exception& e) {
            error = e.what();
            needsSignIn = loadstone::last_error_needs_sign_in();
        }
        wxTheApp->CallAfter([alive, this, kind, releases, error, needsSignIn] {
            if (!alive->load()) return;
            fetchInFlight_ = false;
            for (auto* c : pageControls_) c->Enable(true);
            SetStatusText("");
            if (!error.empty() && needsSignIn) {
                if (OfferSignIn(wxString::FromUTF8(error.c_str()))) StartVersionPick(kind);
                return;
            }
            if (!error.empty()) {
                wxString msg =
                    T("gui-release-list-error", {{"error", wxString::FromUTF8(error.c_str())}}) +
                    "\n\n" + T("gui-release-list-install-latest");
                if (ShowMessage(msg, T("gui-release-list-error-title"),
                                 wxYES_NO | wxICON_QUESTION, this) == wxYES)
                    RunOperation(kind);
                return;
            }
            wxArrayString labels;
            for (const auto& r : releases) labels.Add(FromRust(r.label));
            // Branch ("development") channels the mod declares come after
            // the releases in the same picker.
            size_t releaseCount = releases.size();
            if (pageModel_) {
                for (const auto& c : pageModel_->channels)
                    labels.Add(FromRust(c.label));
            }
            if (labels.IsEmpty()) {
                ShowMessage(T("gui-no-releases"),
                             T("gui-no-releases-title"), wxOK | wxICON_INFORMATION, this);
                return;
            }
            // Default to the newest stable release, like "latest" would.
            int defaultIdx = 0;
            for (size_t i = 0; i < releases.size(); ++i) {
                if (!releases[i].prerelease) {
                    defaultIdx = static_cast<int>(i);
                    break;
                }
            }
            wxSingleChoiceDialog dlg(
                this, T("gui-choose-version"), T("gui-choose-version-title"), labels);
            dlg.SetSelection(defaultIdx);
            if (dlg.ShowModal() != wxID_OK) return;
            int sel = dlg.GetSelection();
            if (sel < 0) return;
            if (static_cast<size_t>(sel) >= releaseCount) {
                size_t channelIdx = static_cast<size_t>(sel) - releaseCount;
                if (!pageModel_ || channelIdx >= pageModel_->channels.size()) return;
                RunOperation(kind, wxString(), wxString(), wxString(),
                             FromRust(pageModel_->channels[channelIdx].id));
                return;
            }
            RunOperation(kind, wxString(), FromRust(releases[sel].tag));
        });
    }).detach();
}

void LoadstoneFrame::RunOperation(OpKind kind, const wxString& actionId,
                                  const wxString& tag,
                                  const wxString& localRelease,
                                  const wxString& channelOverride) {
    if (opInFlight_ || fetchInFlight_) return;
    if (kind == OpKind::Uninstall) {
        wxString name = pageModel_ && !std::string(pageModel_->name).empty()
                            ? FromRust(pageModel_->name)
                            : pageModId_;
        if (ShowMessage(T("gui-confirm-uninstall", {{"name", name}}),
                         T("gui-confirm-uninstall-title"), wxYES_NO | wxICON_QUESTION,
                         this) != wxYES)
            return;
    }
    opInFlight_ = true;
    lastOpKind_ = kind;
    DisablePageControlsKeepFocus();
    if (opLog_) opLog_->Clear();
    SetStatusText(T("gui-status-working"));

    auto alive = alive_;
    auto cb = std::make_shared<GuiUiCallbacks>(alive_, this);
    std::string modId = ToStd(pageModId_);
    std::string game = ToStd(pageGame_);
    const loadstone::CopyPage& copy = pageModel_->copies[currentCopy_];
    // Channel for updates: an explicit channel pick wins; an explicit
    // TAG pick means the release channel (a dev copy's recorded channel
    // would make the engine ignore the tag and reinstall the branch tip);
    // otherwise stay on the channel the copy was installed from.
    std::string channel = !channelOverride.empty() ? ToStd(channelOverride)
                          : !tag.empty()           ? std::string()
                                                   : std::string(copy.channel);
    std::string installChannel = ToStd(channelOverride);
    // The copy's recorded folder addresses state-backed operations
    // (uninstall, actions) even when several copies exist.
    std::string copyDir = std::string(copy.game_dir);
    std::string action = ToStd(actionId);
    std::string tagStr = ToStd(tag);
    std::string local = ToStd(localRelease);
    // The path the user sees (and may have browsed to) is the one the
    // engine gets for installs; empty falls back to auto-detection.
    std::string gameDir = gameDirCtrl_ ? ToStd(gameDirCtrl_->GetValue()) : "";
    // After the reload, land back on the copy this operation targets.
    currentCopyDir_ = (kind == OpKind::Install || kind == OpKind::Update ||
                       kind == OpKind::ChangeOptions)
                          ? wxString::FromUTF8(gameDir.c_str())
                          : wxString::FromUTF8(copyDir.c_str());
    std::thread([alive, this, cb, kind, modId, game, channel, installChannel,
                 copyDir, action, tagStr, local, gameDir] {
        std::string result, error;
        bool needsSignIn = false;
        try {
            switch (kind) {
                case OpKind::Install:
                    // Fresh installs default to stable; only an explicit
                    // channel pick changes that (never the copy's old one).
                    result = std::string(loadstone::run_install(
                        kEmbeddedProfile, "", modId, installChannel, false,
                        tagStr, gameDir, local, false, *cb));
                    break;
                case OpKind::Update:
                    result = std::string(loadstone::run_install(
                        kEmbeddedProfile, "", modId, channel, true, tagStr,
                        gameDir, "", false, *cb));
                    break;
                case OpKind::ChangeOptions:
                    // Reinstall on the copy's channel, asking every install
                    // option again with the current answers preselected.
                    result = std::string(loadstone::run_install(
                        kEmbeddedProfile, "", modId, channel, false, "",
                        gameDir, "", true, *cb));
                    break;
                case OpKind::Uninstall:
                    result = std::string(
                        loadstone::run_uninstall("", game, copyDir, modId, *cb));
                    break;
                case OpKind::Action:
                    result = std::string(loadstone::run_mod_action(
                        "", game, copyDir, modId, action, *cb));
                    break;
                case OpKind::Launch:
                    result = std::string(
                        loadstone::run_launch("", game, copyDir, modId, *cb));
                    break;
            }
        } catch (const std::exception& e) {
            error = e.what();
            needsSignIn = loadstone::last_error_needs_sign_in();
        }
        wxTheApp->CallAfter([alive, this, result, error, needsSignIn] {
            if (alive->load()) OnOpDone(result, error, needsSignIn);
        });
    }).detach();
}

void LoadstoneFrame::StartSelfUpdateCheck() {
    auto alive = alive_;
    std::thread([alive, this] {
        loadstone::SelfUpdate update;
        bool ok = true;
        try {
            update = loadstone::check_self_update(kEmbeddedProfile);
        } catch (...) {
            ok = false; // launch checks never surface errors
        }
        wxTheApp->CallAfter([alive, this, update, ok] {
            if (!alive->load() || !ok || !update.available) return;
            OfferSelfUpdate(update);
        });
    }).detach();
}

void LoadstoneFrame::OfferSelfUpdate(const loadstone::SelfUpdate& update) {
    // Never interrupt running work; the next launch will offer again.
    if (opInFlight_ || fetchInFlight_) return;
    wxString msg = T("gui-self-update-offer", {{"version", update.version},
                                               {"app", profile_.title},
                                               {"current", coreVersion_}});
    if (ShowMessage(msg, T("gui-self-update-title"), wxYES_NO | wxICON_QUESTION, this) !=
        wxYES)
        return;

    opInFlight_ = true;
    SetStatusText(T("gui-status-downloading-update"));
    auto alive = alive_;
    auto cb = std::make_shared<GuiUiCallbacks>(alive_, this);
    loadstone::SelfUpdate chosen = update;
    std::thread([alive, this, cb, chosen] {
        std::string path, error;
        try {
            path = std::string(loadstone::apply_self_update(chosen, *cb));
        } catch (const std::exception& e) {
            error = e.what();
        }
        wxTheApp->CallAfter([alive, this, path, error] {
            if (!alive->load()) return;
            opInFlight_ = false;
            if (!error.empty()) {
                SetStatusText(T("gui-status-update-failed"));
                ShowMessage(wxString::FromUTF8(error.c_str()), T("gui-update-failed-title"),
                             wxOK | wxICON_ERROR, this);
                return;
            }
            SetStatusText(T("gui-status-update-installed"));
            ShowMessage(T("gui-update-installed"),
                         T("gui-update-installed-title"), wxOK | wxICON_INFORMATION, this);
#ifdef __WXOSX__
            // The update replaced the whole .app bundle; LaunchServices
            // starts a new instance of it (-n) while this one quits.
            wxExecute("/usr/bin/open -n \"" + wxString::FromUTF8(path.c_str()) + "\"",
                      wxEXEC_ASYNC);
#else
            wxExecute("\"" + wxString::FromUTF8(path.c_str()) + "\"", wxEXEC_ASYNC);
#endif
            Close(true);
        });
    }).detach();
}

void LoadstoneFrame::OnOpDone(const std::string& result, const std::string& error,
                              bool needsSignIn) {
    opInFlight_ = false;
    if (!error.empty()) {
        SetStatusText(T("gui-status-op-failed"));
        AppendOpLog(wxString::FromUTF8(error.c_str()));
        // A private-repository failure offers sign-in instead of a bare
        // error; either way the page reloads below and the user starts the
        // operation again from it.
        if (needsSignIn)
            OfferSignIn(wxString::FromUTF8(error.c_str()));
        else if (lastOpKind_ == OpKind::Launch)
            // Usually a launch precondition (say, the store client isn't
            // running): something for the user to do, not a fault.
            ShowMessage(wxString::FromUTF8(error.c_str()), T("gui-launch-failed-title"),
                         wxOK | wxICON_WARNING, this);
        else
            ShowMessage(wxString::FromUTF8(error.c_str()), T("gui-op-failed-title"),
                         wxOK | wxICON_ERROR, this);
    } else if (lastOpKind_ == OpKind::Launch) {
        // The game is starting and about to take focus; a modal "Done" box
        // here would fight it for the screen reader's attention.
        SetStatusText(wxString::FromUTF8(result.c_str()));
        AppendOpLog(wxString::FromUTF8(result.c_str()));
    } else {
        SetStatusText(wxString::FromUTF8(result.c_str()));
        ShowMessage(wxString::FromUTF8(result.c_str()), T("gui-op-done-title"),
                     wxOK | wxICON_INFORMATION, this);
    }
    // Reload the page so status, buttons, and settings reflect reality.
    OpenMod(pageModId_);
}

